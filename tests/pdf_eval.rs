const QUERIES: [&str; 10] = [
    "How are herbs watered during dry summer weather?",
    "Repairing a boat before bad weather at the harbor",
    "Observing the moons of a planet through a telescope",
    "How does bread ferment overnight?",
    "INC-18372",
    "Rescuing climbers trapped on frozen mountains",
    "Improving the sound of a wooden violin",
    "Storing power generated by rooftop panels",
    "Restoring the colors of an old painting",
    "Diverting trains around an unsafe bridge",
];

#[test]
#[ignore = "local pinned q8 weights required; synthetic data only; no downloads"]
fn measured_pdf_retrieval_and_exact_evidence() {
    let dir = tempfile::tempdir().unwrap();
    let pdf = dir.path().join("catalog.pdf");
    std::fs::write(&pdf, fixture::pdf(&PAGES, fixture::Kind::Plain)).unwrap();
    let plain = dir.path().join("plain");
    std::fs::create_dir(&plain).unwrap();
    for (i, text) in PAGES.iter().enumerate() {
        let folder = plain.join(format!("{i:02}"));
        std::fs::create_dir(&folder).unwrap();
        std::fs::write(folder.join("catalog.txt"), text).unwrap();
    }
    let load = Instant::now();
    let model = Arc::new(
        EmbeddingGemma2::builder()
            .dimension(128)
            .vision(false)
            .threads(1)
            .build()
            .unwrap(),
    );
    let load_ms = load.elapsed().as_millis();
    let engine = SearchEngine::builder()
        .shared_embedder(model.clone())
        .build()
        .unwrap();
    let baseline = SearchEngine::builder()
        .shared_embedder(model)
        .build()
        .unwrap();
    let cold = Instant::now();
    let indexed = engine.index().paths([&pdf]).execute().unwrap();
    let cold_ms = cold.elapsed().as_millis();
    assert_eq!(indexed.sync.segments_embedded, 20);
    assert!(indexed.sync.skipped.is_empty());
    baseline.index().paths([&plain]).execute().unwrap();
    let mut recall = 0;
    let mut reciprocal = 0.0;
    let mut baseline_recall = 0;
    let mut baseline_reciprocal = 0.0;
    let mut query_ms = Vec::new();
    let mut exact = 0;
    for (i, query) in QUERIES.iter().enumerate() {
        let start = Instant::now();
        let result = engine
            .search(*query)
            .paths([&pdf])
            .mode(SearchMode::Hybrid)
            .limit(10)
            .execute()
            .unwrap();
        query_ms.push(start.elapsed().as_millis());
        assert_eq!(result.stats.sync.segments_embedded, 0);
        let rank = result
            .hits
            .iter()
            .position(
                |h| matches!(h.locator,ResourceLocator::PageText{page,..} if page==i as u32+1),
            )
            .map(|r| r + 1);
        if let Some(r) = rank {
            if r <= 5 {
                recall += 1;
            }
            reciprocal += 1.0 / r as f64;
        }
        let base = baseline
            .search(*query)
            .paths([&plain])
            .mode(SearchMode::Hybrid)
            .limit(10)
            .execute()
            .unwrap();
        let base_rank = base
            .hits
            .iter()
            .position(|h| {
                h.resource
                    .to_file_path()
                    .unwrap()
                    .parent()
                    .unwrap()
                    .file_name()
                    .unwrap()
                    == format!("{i:02}").as_str()
            })
            .map(|r| r + 1);
        if let Some(r) = base_rank {
            if r <= 5 {
                baseline_recall += 1;
            }
            baseline_reciprocal += 1.0 / r as f64;
        }
        println!(
            "query {}: PDF rank {:?}, text rank {:?}",
            i + 1,
            rank,
            base_rank
        );
    }
    let all = engine
        .search("catalog.pdf")
        .paths([&pdf])
        .limit(30)
        .execute()
        .unwrap();
    assert!(all.hits[0].signals.filename);
    for hit in all.hits {
        let ResourceLocator::PageText { page, .. } = hit.locator else {
            panic!("expected PDF locator")
        };
        assert_eq!(engine.extract(&hit).unwrap().text, PAGES[page as usize - 1]);
        exact += 1;
    }
    query_ms.sort();
    println!(
        "PDF_EVAL pages=20 queries=10 Recall@5={:.3} MRR@10={:.3} text_Recall@5={:.3} text_MRR@10={:.3} exact={exact}/20 load_ms={load_ms} cold_index_ms={cold_ms} warm_query_p50_ms={} warm_query_p95_ms={}",
        recall as f64 / 10.0,
        reciprocal / 10.0,
        baseline_recall as f64 / 10.0,
        baseline_reciprocal / 10.0,
        query_ms[4],
        query_ms[9]
    );
    assert!(recall >= 9, "E6: text PDF Recall@5 below 90%: {recall}/10");
    assert_eq!(exact, 20, "E6: evidence correctness gate");
}
