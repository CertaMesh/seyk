#!/usr/bin/env python3
"""Generate deterministic feature and embedding goldens using pinned LOCAL weights.
Requires transformers==5.19.0, torch==2.14.1, numpy; never downloads.
Input audio_signal.f32 is generated by the Rust audio_signal example.
"""
import hashlib, json
from pathlib import Path
import numpy as np
import torch, transformers
from transformers import AutoConfig, AutoModel, AutoProcessor

assert transformers.__version__ == '5.19.0'
assert torch.__version__ == '2.14.1'
torch.set_num_threads(1)
ROOT = Path(__file__).resolve().parents[2]/'crates/seyk-embeddinggemma/tests/fixtures/audio'
HUB = Path.home()/'.cache/huggingface/hub'
MODEL=HUB/'models--google--embeddinggemma-2/snapshots/914f7f89142e33e77833254d9c9b90c3cef7303b'
EXPORT=HUB/'models--onnx-community--embeddinggemma-2-ONNX/snapshots/daa72c51243991dfcaf9f9137d2c573d8f7790c0'
processor=AutoProcessor.from_pretrained(EXPORT,local_files_only=True)
config=AutoConfig.from_pretrained(MODEL,local_files_only=True); config.vision_config=None
model=AutoModel.from_pretrained(MODEL,config=config,dtype=torch.float32,local_files_only=True).eval()
source=Path(transformers.__file__).parent
base=np.fromfile(ROOT/'audio_signal.f32',dtype='<f4')
for name, length in [('reference',16000), ('tail',16001), ('full',160000)]:
    samples=np.resize(base,length)
    encoded=processor(audio=samples,sampling_rate=16000,return_tensors='pt')
    features=encoded['input_features'][0].numpy()
    feature_name='features.f32' if name=='reference' else f'{name}-features.f32'
    features.astype('<f4').tofile(ROOT/feature_name)
    with torch.no_grad():
        output=model(**encoded)
        att=encoded['attention_mask'].unsqueeze(-1)
        vector=(output.last_hidden_state*att).sum(1)/att.sum(1)
        vector=torch.nn.functional.normalize(vector,dim=1)[0].numpy()
    record=dict(transformers_version=transformers.__version__,torch_version=torch.__version__,model_revision=MODEL.name,onnx_revision=EXPORT.name,signal_sha256=hashlib.sha256(samples.astype('<f4').tobytes()).hexdigest(),features_shape=list(features.shape),mask=encoded['input_features_mask'][0].tolist(),input_ids=encoded['input_ids'][0].tolist(),embedding=vector.tolist(),reference_source_sha256={str(p.relative_to(source)):hashlib.sha256(p.read_bytes()).hexdigest() for p in [source/'models/gemma4/feature_extraction_gemma4.py',source/'models/embedding_gemma2/processing_embedding_gemma2.py',source/'models/embedding_gemma2/modeling_embedding_gemma2.py']})
    (ROOT/f'{name}.json').write_text(json.dumps(record,indent=2)+'\n')
    print('GOLDEN',name,record['features_shape'],sum(record['mask']),record['input_ids'].count(258881),flush=True)
